/**
 * Go runner (execution side of the Go loop).
 *
 * Mirrors `PythonRunner` but respects the two things that make Go different:
 *
 *  1. **It is compiled.** A snippet is written to disk, `go build` produces a
 *     real binary, and *that* is what runs. Doing build-then-run (rather than
 *     `go run`) matters for a test harness: `go run` collapses every non-zero
 *     program exit into exit status 1, so a suite that fails would be
 *     indistinguishable from one that passed with a warning. Running the
 *     binary directly preserves the exact exit code.
 *
 *  2. **There is no REPL state.** Python keeps a pickled namespace between
 *     runs; Go cannot. A "session" here is a shared directory plus a `go.mod`,
 *     so consecutive snippets compile in the same module (which is also what
 *     makes `go test` work).
 *
 * Build and run are reported as separate phases, so a compile error is visibly
 * different from a runtime failure in the Output tab.
 */
import { spawn } from 'node:child_process';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { performance } from 'node:perf_hooks';
import { ulid } from '../util/ulid.js';
import { resolveGoBin } from './discover.js';
import { OutputDecoder } from '../util/encoding.js';
import type { Kernel } from '../kernel/Kernel.js';

export type GoMode = 'run' | 'test';

export interface GoRunOptions {
  /** Snippet source. Mutually exclusive with `file`. */
  code?: string;
  /** Run an existing file instead of a snippet. */
  file?: string;
  /** Session id: reuse to share the module dir across runs. */
  sessionId?: string;
  /** `run` builds+runs a main package; `test` runs `go test -v`. */
  mode?: GoMode;
  /** Extra argv forwarded to the built binary (run) or `go test` (test). */
  args?: string[];
  /** Hard timeout in ms (covers build + run). */
  timeoutMs?: number;
  /** Working directory override. */
  cwd?: string;
  /** Capture each output line as a log record (default true). */
  captureOutput?: boolean;
}

export interface GoRunResult {
  sessionId: string;
  runId: string;
  exitCode: number | null;
  signal: string | null;
  durationMs: number;
  stdout: string;
  stderr: string;
  stdoutTruncated?: boolean;
  stderrTruncated?: boolean;
  logLinesTruncated?: boolean;
  timedOut: boolean;
  logLines: number;
  goBin: string;
  mode: GoMode;
  /** Which phase produced the outcome. */
  phase: 'build' | 'run' | 'test';
  /** True when the compiler rejected the source (no binary was produced). */
  compileError: boolean;
  /** Wall time spent in `go build` (0 in test mode). */
  buildMs: number;
  scriptPath?: string;
}

interface Session {
  id: string;
  dir: string;
  modPath: string;
}

const MOD_FILE = `// Generated by Nolanguage — one module per execution session.
module nolanguage/session

go 1.21
`;

export class GoRunner {
  private sessions = new Map<string, Session>();
  private readonly goBin: string;
  private readonly resolved: { bin: string; source: string };

  constructor(private kernel: Kernel, goBin?: string) {
    this.resolved = resolveGoBin(goBin ?? process.env.GO_BIN);
    this.goBin = this.resolved.bin;
  }

  get binary(): string {
    return this.goBin;
  }

  /** Where the toolchain was found (for the status bar / diagnostics). */
  get discovery(): { bin: string; source: string } {
    return this.resolved;
  }

  /**
   * True when a usable `go` binary was located. When false the runner still
   * reports a clear error instead of throwing at an awkward moment.
   */
  get available(): boolean {
    return this.resolved.source !== 'missing';
  }

  async session(sessionId?: string): Promise<Session> {
    const id = sessionId ?? `sess-${ulid().slice(-10)}`;
    let s = this.sessions.get(id);
    if (!s) {
      const dir = await mkdtemp(join(tmpdir(), 'nolanguage-go-'));
      s = { id, dir, modPath: join(dir, 'go.mod') };
      await writeFile(s.modPath, MOD_FILE, 'utf8');
      this.sessions.set(id, s);
      this.kernel.logger
        .forExecution('execution.session', id)
        .info('Go session created', { sessionId: id, dir, go: this.goBin });
    }
    return s;
  }

  /** Drop a session: its module dir is removed and the next run starts clean. */
  async resetSession(sessionId: string): Promise<boolean> {
    const s = this.sessions.get(sessionId);
    if (!s) return false;
    await rm(s.dir, { recursive: true, force: true }).catch(() => undefined);
    this.sessions.delete(sessionId);
    this.kernel.logger
      .forExecution('execution.session', sessionId)
      .info('Go session reset', { sessionId });
    return true;
  }

  sessionCount(): number {
    return this.sessions.size;
  }

  async run(opts: GoRunOptions): Promise<GoRunResult> {
    const mode: GoMode = opts.mode ?? 'run';
    const session = await this.session(opts.sessionId);
    const runId = `run-${ulid().slice(-10)}`;
    const log = this.kernel.logger
      .forExecution(`execution.go`, session.id)
      .withContext({ sessionId: session.id, requestId: runId });

    const span = this.kernel.tracer.startSpan('execution.run', {
      attributes: { languageId: 'go', sessionId: session.id, runId, mode },
    });
    const runLog = log.span(span);

    if (!this.available) {
      const message =
        `Go toolchain not found (looked for GO_BIN, then PATH, then known install dirs). ` +
        `Install Go and set GO_BIN to go.exe.`;
      runLog.error('Go toolchain unavailable', { go: this.goBin });
      span.setAttribute('exitCode', -1).end();
      return {
        sessionId: session.id,
        runId,
        exitCode: -1,
        signal: null,
        durationMs: 0,
        stdout: '',
        stderr: message + '\n',
        timedOut: false,
        logLines: 0,
        goBin: this.goBin,
        mode,
        phase: mode === 'test' ? 'test' : 'build',
        compileError: true,
        buildMs: 0,
      };
    }

    // ---- materialise the source ----
    let scriptPath: string;
    if (opts.code !== undefined) {
      // A `*_test.go` name is required by the go tool for test mode; the
      // package clause is the user's responsibility (samples provide it).
      scriptPath = join(session.dir, mode === 'test' ? 'main_test.go' : 'main.go');
      await writeFile(scriptPath, opts.code, 'utf8');
      if (mode === 'test') {
        // Remove a stale non-test main.go from a previous run-mode execution so
        // `go test` does not trip over two `func main`s.
        await rm(join(session.dir, 'main.go'), { force: true }).catch(() => undefined);
      } else {
        await rm(join(session.dir, 'main_test.go'), { force: true }).catch(() => undefined);
      }
    } else if (opts.file) {
      scriptPath = opts.file;
    } else {
      throw new Error('GoRunner.run requires either `code` or `file`');
    }

    const cwd = opts.cwd ?? session.dir;
    const timeoutMs = opts.timeoutMs ?? 20_000;
    const t0 = performance.now();
    const env = this.childEnv();
    const capture = opts.captureOutput !== false;
    const userLog = this.kernel.logger.forUserCode('go', session.id);

    const stdoutChunks: string[] = [];
    const stderrChunks: string[] = [];
    const decoders = { stdout: new OutputDecoder(), stderr: new OutputDecoder() };
    const OUTPUT_LIMIT = 4 * 1024 * 1024;
    const LOG_LINE_LIMIT = 10_000;
    let stdoutBytes = 0, stderrBytes = 0;
    let stdoutTruncated = false, stderrTruncated = false, logLinesTruncated = false;
    let logLines = 0;
    const stdoutResult = () => stdoutChunks.join('') + decoders.stdout.flush() + (stdoutTruncated ? `\n[stdout truncated at ${OUTPUT_LIMIT} bytes]\n` : '');
    const stderrResult = () => stderrChunks.join('') + decoders.stderr.flush() + (stderrTruncated ? `\n[stderr truncated at ${OUTPUT_LIMIT} bytes]\n` : '');

    const onLine = (stream: 'stdout' | 'stderr') => (chunk: Buffer): void => {
      const text = decoders[stream].push(chunk);
      const list = stream === 'stdout' ? stdoutChunks : stderrChunks;
      const used = stream === 'stdout' ? stdoutBytes : stderrBytes;
      const remaining = Math.max(0, OUTPUT_LIMIT - used);
      let accepted = text;
      if (Buffer.byteLength(text) > remaining) {
        let lo = 0, hi = text.length;
        while (lo < hi) {
          const mid = Math.ceil((lo + hi) / 2);
          if (Buffer.byteLength(text.slice(0, mid)) <= remaining) lo = mid;
          else hi = mid - 1;
        }
        accepted = text.slice(0, lo);
        if (stream === 'stdout') stdoutTruncated = true; else stderrTruncated = true;
      }
      if (accepted) list.push(accepted);
      const acceptedBytes = Buffer.byteLength(accepted);
      if (stream === 'stdout') stdoutBytes += acceptedBytes; else stderrBytes += acceptedBytes;
      if (!capture) return;
      for (const raw of accepted.split('\n')) {
        const line = raw.replace(/\r$/, '');
        if (!line.trim()) continue;
        if (logLines >= LOG_LINE_LIMIT) { logLinesTruncated = true; continue; }
        const logged = line.length > 16 * 1024 ? `${line.slice(0, 16 * 1024)}… [line truncated]` : line;
        if (logged !== line) logLinesTruncated = true;
        logLines++;
        const fields = { stream, runId, line: logLines };
        if (stream === 'stderr') {
          // Compiler diagnostics look like `./main.go:12:5: undefined: foo`.
          if (/^\s*[.\w/\\-]+\.go:\d+:\d+:/.test(logged) || /^(#|\s*panic:|\s*FAIL)/.test(logged)) {
            userLog.error(logged, fields);
          } else {
            userLog.warn(logged, fields);
          }
        } else {
          userLog.info(logged, fields);
        }
      }
    };

    let timedOut = false;
    const killAfter = (child: { kill(sig?: NodeJS.Signals): boolean }): NodeJS.Timeout =>
      setTimeout(() => {
        timedOut = true;
        runLog.error('Execution timed out', { timeoutMs, sessionId: session.id });
        child.kill('SIGKILL');
      }, timeoutMs);

    // ---------------- phase 1: build (run mode only) ----------------
    let buildMs = 0;
    let compileError = false;
    let binPath = '';

    if (mode === 'run') {
      binPath = join(session.dir, `${runId}${process.platform === 'win32' ? '.exe' : ''}`);
      runLog.info('Building Go program', { script: scriptPath, cwd, go: this.goBin });
      const b0 = performance.now();
      const build = spawn(this.goBin, ['build', '-o', binPath, scriptPath], {
        cwd,
        env,
        windowsHide: true,
      });
      build.stdout.on('data', onLine('stdout'));
      build.stderr.on('data', onLine('stderr'));
      const bt = killAfter(build);
      const buildExit = await waitExit(build);
      clearTimeout(bt);
      buildMs = performance.now() - b0;
      this.kernel.perfMetrics().record('execution.go.build', buildMs);

      if (timedOut || buildExit.code !== 0) {
        compileError = !timedOut;
        const durationMs = performance.now() - t0;
        this.finish(log, span, {
          ok: false,
          durationMs,
          logLines,
          exitCode: buildExit.code,
          mode,
          phase: 'build',
          compileError,
          timedOut,
        });
        return {
          sessionId: session.id,
          runId,
          exitCode: buildExit.code,
          signal: buildExit.signal,
          durationMs,
          stdout: stdoutResult(),
          stderr: stderrResult(),
          stdoutTruncated,
          stderrTruncated,
          logLinesTruncated,
          timedOut,
          logLines,
          goBin: this.goBin,
          mode,
          phase: 'build',
          compileError,
          buildMs,
          scriptPath: opts.file,
        };
      }
      runLog.info('Build succeeded', { buildMs: Math.round(buildMs), binary: binPath });
    }

    // ---------------- phase 2: run / test ----------------
    const argv =
      mode === 'test'
        ? ['test', '-v', '-count=1', ...(opts.args ?? []), '.']
        : [binPath, ...(opts.args ?? [])];
    const command = mode === 'test' ? this.goBin : binPath;
    runLog.info(mode === 'test' ? 'Running go test' : 'Running Go binary', {
      command,
      args: argv.join(' '),
      cwd,
    });

    const child = spawn(command, argv, { cwd, env, windowsHide: true });
    child.stdout.on('data', onLine('stdout'));
    child.stderr.on('data', onLine('stderr'));
    const timer = killAfter(child);
    const exit = await waitExit(child);
    clearTimeout(timer);

    const durationMs = performance.now() - t0;
    const m = this.kernel.perfMetrics();
    m.record('execution.run', durationMs);
    m.record('execution.go.run', durationMs);
    m.record('execution.lines', logLines);

    const phase: GoRunResult['phase'] = mode === 'test' ? 'test' : 'run';
    this.finish(log, span, {
      ok: exit.code === 0 && !timedOut,
      durationMs,
      logLines,
      exitCode: exit.code,
      mode,
      phase,
      compileError: false,
      timedOut,
    });

    return {
      sessionId: session.id,
      runId,
      exitCode: exit.code,
      signal: exit.signal,
      durationMs,
      stdout: stdoutResult(),
      stderr: stderrResult(),
      stdoutTruncated,
      stderrTruncated,
      logLinesTruncated,
      timedOut,
      logLines,
      goBin: this.goBin,
      mode,
      phase,
      compileError: false,
      buildMs,
      scriptPath: opts.file,
    };
  }

  async close(): Promise<void> {
    for (const s of this.sessions.values()) {
      await rm(s.dir, { recursive: true, force: true }).catch(() => undefined);
    }
    this.sessions.clear();
  }

  // ---------------- internals ----------------

  /**
   * Environment for every `go` child. PATH is prefixed with the toolchain's bin
   * dir so the go tool can find its own helpers (gofmt, vet) even when the user
   * has not added Go to their PATH.
   */
  private childEnv(): NodeJS.ProcessEnv {
    const dir = this.goBin.replace(/[\\/][^\\/]+$/, '');
    // When the toolchain was found on PATH, `goBin` is the bare name `go` and
    // the regex above matches nothing — prefixing PATH with "go" would add a
    // junk entry. Only prefix when we actually have a directory.
    const binDir = dir === this.goBin ? '' : dir;
    const sep = process.platform === 'win32' ? ';' : ':';
    const path = process.env.PATH ?? '';
    return {
      ...process.env,
      PATH: binDir ? binDir + sep + path : path,
      GOTOOLCHAIN: process.env.GOTOOLCHAIN ?? 'local',
    };
  }

  private finish(
    log: { info: (m: string, f?: Record<string, unknown>) => void; error: (m: string, f?: Record<string, unknown>) => void },
    span: { setAttribute: (k: string, v: unknown) => { end: () => void } },
    o: {
      ok: boolean;
      durationMs: number;
      logLines: number;
      exitCode: number | null;
      mode: GoMode;
      phase: string;
      compileError: boolean;
      timedOut: boolean;
    },
  ): void {
    const fields = {
      durationMs: Math.round(o.durationMs),
      lines: o.logLines,
      exitCode: o.exitCode,
      mode: o.mode,
      phase: o.phase,
      compileError: o.compileError,
      timedOut: o.timedOut,
    };
    if (o.ok) log.info('Go finished', fields);
    else if (o.compileError) log.error('Go build failed', fields);
    else log.error('Go failed', fields);
    span.setAttribute('exitCode', o.exitCode).end();
  }
}

/** Await a child's exit, tolerating spawn failures. */
function waitExit(child: {
  on(ev: 'error', cb: (e: Error) => void): unknown;
  on(ev: 'close', cb: (code: number | null, signal: string | null) => void): unknown;
}): Promise<{ code: number | null; signal: string | null }> {
  return new Promise((resolve) => {
    child.on('error', () => resolve({ code: -1, signal: null }));
    child.on('close', (code, signal) => resolve({ code, signal: signal ?? null }));
  });
}
